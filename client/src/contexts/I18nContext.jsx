const I18nContext = createContext(null);

export const useI18n = () => {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
};

export const I18nProvider = ({ children }) => {
  const [lang, setLang] = useState(() => {
    return localStorage.getItem('gestpharma_lang') || 'fr';
  });

  useEffect(() => {
    localStorage.setItem('gestpharma_lang', lang);
    const langObj = LANGUAGES.find((l) => l.code === lang);
    document.documentElement.setAttribute('lang', lang);
    document.documentElement.setAttribute('dir', langObj?.dir || 'ltr');
  }, [lang]);

  const t = useCallback(
    (key) => TRANSLATIONS[lang]?.[key] ?? TRANSLATIONS['fr']?.[key] ?? key,
    [lang]
  );

  const currentLang = LANGUAGES.find((l) => l.code === lang) || LANGUAGES[0];

  return (
    <I18nContext.Provider value={{ lang, setLang, t, currentLang, LANGUAGES }}>
      {children}
    </I18nContext.Provider>
  );
};

export default I18nContext;
